// 질문 은행 — Claude 가 연결돼 있지 않거나 실패했을 때 쓰는 대비용. 파일명이 _ 로 시작해 라우트로 노출되지 않는다.
// 질문 본문은 _qbank.json 에 있다(약 1000개 — 코드와 데이터를 나눴다). 이 파일은 그것을 읽어 꼬리 문장을 붙여 DAILY·WEEKLY 로 내줄 뿐이다.
//   daily : 오늘의 질문(평일 아침, 한 사람이 혼자 답하는 편안한 질문). 요일마다 종류가 돌아간다(api/_routine.js TYPE_BY_DOW)
//           종류 = HR | 커리어 | 상식 | 일상.  상식·일상은 «자유», 커리어는 «커리어», HR 은 해당 분류로 올라간다.
//   weekly: 이번 주 토론(팀 전체가 일주일간 댓글로 의논) — 구체적인 상황과 제약을 주고 «어떻게 풀겠는가 / 어떻게 통과해 왔는가» 를 묻는다.
//   id    : d0001… / w001… — 질문마다 영구 번호. 일러스트는 R2 qimg/<id>.jpg(api/_qimg.js 가 글에 붙인다). 번호는 바꾸지 말고 뒤에만 덧붙인다.
// 새 질문·그림 만드는 법은 CLAUDE.md «질문 일러스트» 절. 검증: node scripts/check_questions.js (중복·길이·분류·민감어·종류별 개수·그림 장면)
// 쓰지 않는 소재: 구체적인 급여 액수, 나이, 결혼·가족, 종교, 정치, 건강 — 답하기 불편할 수 있는 것은 처음부터 뺐다.
const J = require("./_qbank.json");
const TAIL = { HR: "\n\n편하게 3~5문장으로 답해 주세요. 정답은 없어요.", 커리어: "\n\n편하게 3~5문장으로 답해 주세요. 정답은 없어요.", 일상: "\n\n한두 문장이면 충분해요. 편하게 적어 주세요.", 상식: "\n\n정확하지 않아도 괜찮아요. 아는 만큼, 느낀 만큼만 적어 주세요." };
const ASK = "\n\n이렇게 이야기해 보면 좋아요.\n1) 내가 담당자라면 어떤 순서로 풀어 갈지\n2) 비슷한 상황을 겪었거나 지켜봤다면 어떻게 지나왔는지\n3) 이때 절대 하지 말아야 할 한 가지";

const DAILY = J.daily.map((q) => ({ ...q, body: q.hint + TAIL[q.type] }));
const WEEKLY = J.weekly.map((q) => ({ ...q, body: q.hint + ASK }));

module.exports = { DAILY, WEEKLY, ASK, TAIL };
